<?php

namespace App\Enums;

/**
 * Встроенные ответы бота — тексты, которые бот отправляет сам, вне блоков
 * сценария (фолбэки транспорта и завершённых запусков). Значения без точек:
 * они же — имена полей формы Filament, точка дала бы вложенный statePath.
 */
enum BotReplyKey: string
{
    case StaleButton = 'stale_button';

    /**
     * Meta fails to deliver which button was pressed for some WhatsApp Web
     * devices migrated to LID identifiers (escalated to Meta, no ETA) — the
     * choice is unrecoverable, so the bot only explains and takes no
     * further action.
     */
    case UnrecognizedPress = 'unrecognized_press';

    case RunDecisionFinal = 'run_decision_final';

    /**
     * На AI-шаге человек спросил про сам сервис, а не про своё объявление
     * или поиск: бот отвечает этим текстом и повторяет свой вопрос, не
     * тратя попытку уточнения.
     */
    case ServiceQuestion = 'service_question';

    case NavRouteOffer = 'nav_route_offer';

    case NavResumeOffer = 'nav_resume_offer';

    case NavResumed = 'nav_resumed';

    case CollectExitConfirm = 'collect_exit_confirm';

    /** Стандартный текст — используется, пока оператор не задал свой. */
    public function default(): string
    {
        return match ($this) {
            self::StaleButton => 'Эта кнопка из прежней версии бота и больше не действует.',
            self::UnrecognizedPress => 'Не получилось распознать нажатие кнопки. Если это была кнопка из уведомления о заявке или объявлении — ответьте, пожалуйста, с телефона.',
            self::RunDecisionFinal => 'Этот вопрос уже закрыт — ответ был зафиксирован ранее.',
            self::ServiceQuestion => 'На такие вопросы отвечает наш оператор — он видит эту переписку. Вернёмся к делу.',
            self::NavRouteOffer => 'Похоже, вам нужно «%s». Перейти?',
            self::NavResumeOffer => 'Похоже, вы хотите вернуться к прерванной анкете. Продолжить её?',
            self::NavResumed => 'Возвращаемся к анкете — всё написанное на месте.',
            self::CollectExitConfirm => 'Прервать анкету? Всё написанное сохранится — сможете продолжить позже.',
        };
    }

    public function label(): string
    {
        return match ($this) {
            self::StaleButton => 'Кнопка из прежней версии бота',
            self::UnrecognizedPress => 'Нажатие кнопки не распознано',
            self::RunDecisionFinal => 'Вопрос уже закрыт',
            self::ServiceQuestion => 'Вопрос про сервис на AI-шаге',
            self::NavRouteOffer => 'Предложение перейти в другой раздел',
            self::NavResumeOffer => 'Предложение продолжить анкету',
            self::NavResumed => 'Возврат к прерванной анкете',
            self::CollectExitConfirm => 'Подтверждение выхода из анкеты',
        };
    }

    /** Когда отправляется — для подсказки формы и справки в редакторе. */
    public function description(): string
    {
        return match ($this) {
            self::StaleButton => 'Отправляется, когда контакт нажал кнопку, которой нет в текущей опубликованной версии сценария; после текста бот повторяет текущий шаг или начинает диалог заново.',
            self::UnrecognizedPress => 'WhatsApp не смог передать, какая кнопка нажата (бывает в WhatsApp Web). Бот отправляет только это пояснение и больше ничего не делает: активный диалог остаётся на текущем шаге, новый не начинается. Кнопки уведомлений о заявке или объявлении при таком сбое восстановить нельзя — стандартный текст советует ответить с телефона.',
            self::RunDecisionFinal => 'Отправляется при нажатии кнопки уже завершённого запуска — например, второй кнопки того же уведомления после принятого решения.',
            self::ServiceQuestion => 'Отправляется, когда на шаге «Запрос ввода (AI)» человек спрашивает про сам сервис (сколько стоит размещение, как долго висит объявление), а не про своё объявление или поиск. Попытка уточнения при этом не тратится, вопрос не попадает в данные объявления, и следом бот повторяет свой текущий вопрос.',
            self::NavRouteOffer => 'Отправляется, когда маршрутизатор со средней уверенностью определяет, что сообщение относится к другому разделу меню; `%s` — название кнопки-цели, подставляется через sprintf. К тексту добавляется кнопка «Перейти».',
            self::NavResumeOffer => 'Отправляется, когда маршрутизатор со средней уверенностью определяет попытку вернуться к прерванной анкете. К тексту добавляется кнопка «Продолжить».',
            self::NavResumed => 'Отправляется перед тем, как диалог возвращается на прерванный шаг анкеты — сразу после того, как контакт согласился её продолжить.',
            self::CollectExitConfirm => 'Отправляется, когда контакт пытается выйти из непустой анкеты — с кнопками «Да, в меню» и «Продолжить анкету».',
        };
    }
}

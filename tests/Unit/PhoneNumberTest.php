<?php

use App\Support\PhoneNumber;

test('номер приводится к тому виду, в котором его хранит WhatsApp', function (?string $typed, ?string $expected) {
    expect(PhoneNumber::normalize($typed))->toBe($expected);
})->with([
    'как диктуют по телефону' => ['8 701 234 56 78', '77012345678'],
    'с плюсом и скобками' => ['+7 (701) 234-56-78', '77012345678'],
    'через дефисы' => ['7701-234-56-78', '77012345678'],
    'уже канонический' => ['77012345678', '77012345678'],
    'пустая строка' => ['', null],
    'без цифр' => ['Асхат', null],
    'ничего не введено' => [null, null],
    // Ведущая 8 меняется на 7 только у казахстанских номеров (все они
    // начинаются с 7 7): иностранный номер с ведущей 8 не трогаем.
    'иностранный номер с ведущей 8' => ['81312345678', '81312345678'],
    // До полной длины решать нечего — обрывок остаётся как есть.
    'недобранный номер' => ['8701234', '8701234'],
]);

test('поиск по номеру предлагает оба написания, пока оператор ещё печатает', function () {
    expect(PhoneNumber::searchPrefixes('8 701'))->toBe(['8701', '7701'])
        ->and(PhoneNumber::searchPrefixes('+7 701'))->toBe(['7701'])
        ->and(PhoneNumber::searchPrefixes('Асхат'))->toBe([]);
});
